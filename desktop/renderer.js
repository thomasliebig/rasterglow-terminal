function paletteColor(index) {
  if (index < 16) return ansi16[index];
  if (index < 232) {
    const n = index - 16;
    const r = Math.floor(n / 36), g = Math.floor((n % 36) / 6), b = n % 6;
    const level = value => value === 0 ? 0 : 55 + value * 40;
    return `rgb(${level(r)},${level(g)},${level(b)})`;
  }
  const gray = 8 + (index - 232) * 10;
  return `rgb(${gray},${gray},${gray})`;
}

function cssRgb(color) {
  if (color[0] === '#') {
    const n = parseInt(color.slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  return color.match(/\d+/g).slice(0, 3).map(Number);
}

function sourceFgRgb(cell) {
  if (cell.isFgRGB()) {
    const rgb = cell.getFgColor();
    return [(rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255];
  }
  if (cell.isFgPalette()) return cssRgb(paletteColor(cell.getFgColor()));
  return [150, 220, 170];
}

function sourceBgRgb(cell) {
  if (cell.isBgRGB()) {
    const rgb = cell.getBgColor();
    return [(rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255];
  }
  if (cell.isBgPalette()) return cssRgb(paletteColor(cell.getBgColor()));
  return null;
}

function phosphorLevel(rgb, floor = 0.035) {
  if (!rgb) return 0;
  const [r, g, b] = rgb;
  // Convert sRGB to linear light and then to perceptual CIE L*. This keeps
  // equally perceived ANSI colors equally separated on one green phosphor.
  const linear = value => {
    const s = value / 255;
    return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  const luminance = 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
  const lightness = luminance <= 216 / 24389
    ? luminance * (24389 / 27) / 100
    : (116 * Math.cbrt(luminance) - 16) / 100;
  return floor + (1 - floor) * lightness;
}

function green(level) {
  return `rgb(${Math.round(42 * level)},${Math.round(255 * level)},${Math.round(102 * level)})`;
}

function cellPaint(cell) {
  let fg = sourceFgRgb(cell);
  let bg = sourceBgRgb(cell);
  if (cell.isInverse()) [fg, bg] = [bg, fg];
  let fgLevel = fg ? phosphorLevel(fg, 0.035) : 0;
  if (cell.isBold()) fgLevel = Math.min(1, fgLevel * 1.16);
  return {
    fg: fg ? green(fgLevel) : 'rgb(0,0,0)',
    bg: bg ? green(0.018 + phosphorLevel(bg, 0) * 0.255) : null
  };
}
