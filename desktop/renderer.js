function compileShader(type, source) {
  const shader = gl.createShader(type);
  gl.shaderSource(shader, source); gl.compileShader(shader);
  if (!gl.getShaderParameter(shader, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(shader));
  return shader;
}

const glProgram = gl.createProgram();
gl.attachShader(glProgram, compileShader(gl.VERTEX_SHADER, `
  attribute vec2 p; varying vec2 uv;
  void main(){ uv=p*.5+.5; gl_Position=vec4(p,0.,1.); }
`));
gl.attachShader(glProgram, compileShader(gl.FRAGMENT_SHADER, `
  precision mediump float; varying vec2 uv; uniform sampler2D phosphor; uniform sampler2D liveText;
  uniform float barrel; uniform float brightness; uniform float contrast; uniform float focus; uniform float glow;
  uniform float flicker; uniform float time; uniform vec2 resolution;
  float noise2(vec2 p){ return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453); }
  void main(){
    vec2 q=uv*2.0-1.0;
    vec2 source=q*(1.0+barrel*dot(q,q));
    vec2 suv=source*.5+.5;
    // Each small group of raster lines is redrawn with a tiny independent
    // horizontal timing error. Rare wider bands emulate a brief sync wobble.
    float frame=floor(time*32.0);
    float rasterRow=floor(suv.y*resolution.y/2.0);
    float rowNoise=noise2(vec2(rasterRow,frame));
    float band=floor(suv.y*28.0);
    float bandNoise=noise2(vec2(band,floor(time*11.0)));
    float rareBand=step(0.965,bandNoise)*(bandNoise-0.965)/0.035;
    suv.x+=(rowNoise-0.5)*flicker*0.75/resolution.x;
    suv.x+=(noise2(vec2(band,frame))-0.5)*rareBand*flicker*4.0/resolution.x;
    if(suv.x<0.0||suv.x>1.0||suv.y<0.0||suv.y>1.0){ gl_FragColor=vec4(.001,.006,.003,1.); return; }
    vec3 history=texture2D(phosphor,suv).rgb;
    vec3 live=texture2D(liveText,suv).rgb;
    float liveMask=max(live.r,max(live.g,live.b));
    vec3 c=max(live*0.98,history*(1.0-liveMask*focus));
    vec2 px=1.0/resolution;
    vec3 halo=texture2D(phosphor,suv+vec2( 2.0, 0.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2(-2.0, 0.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2( 0.0, 2.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2( 0.0,-2.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2( 4.0, 3.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2(-4.0,-3.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2( 4.0,-3.0)*px).rgb;
    halo+=texture2D(phosphor,suv+vec2(-4.0, 3.0)*px).rgb;
    c+=halo*(0.055*glow);
    float lineGrain=(noise2(vec2(rasterRow,frame+19.0))-0.5)*0.045*flicker;
    float mains=1.0+sin(time*6.2831853*50.0)*0.006*flicker;
    c=max(c+lineGrain,0.0)*mains;
    // Contrast changes the spacing of phosphor intensities (gamma around
    // black); brightness remains an independent beam-current multiplier.
    float beam=max(c.r,max(c.g,c.b));
    float contrasted=pow(clamp(beam,0.0,1.0),contrast)*brightness;
    c*=contrasted/max(beam,0.0001);
    float scanPhase=suv.y*resolution.y*1.5707963;
    float scanline=0.90+0.10*sin(scanPhase);
    float fineBeam=0.98+0.02*sin(scanPhase*2.0);
    c*=scanline*fineBeam;
    float vignette=clamp(1.16-dot(q,q)*.24,0.0,1.0);
    gl_FragColor=vec4(c*vignette,1.0);
  }
`));
