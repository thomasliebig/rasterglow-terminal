// Two GPU textures retain per-pixel phosphor energy. One is read while the
// other is written, then they swap roles (ping-pong feedback).
const feedbackProgram = gl.createProgram();
gl.attachShader(feedbackProgram, compileShader(gl.VERTEX_SHADER, `
  attribute vec2 p; varying vec2 uv;
  void main(){ uv=p*.5+.5; gl_Position=vec4(p,0.,1.); }
`));
gl.attachShader(feedbackProgram, compileShader(gl.FRAGMENT_SHADER, `
  precision mediump float; varying vec2 uv;
  uniform sampler2D previousEnergy; uniform sampler2D currentLight;
  uniform float retention; uniform float charge;
  void main(){
    vec3 oldEnergy=texture2D(previousEnergy,uv).rgb;
    vec3 exposure=texture2D(currentLight,uv).rgb;
    // Charge towards the actual emitted intensity, never towards white.
    // When the beam becomes darker, retain and decay the previous energy.
    vec3 rising=mix(oldEnergy,exposure,charge);
    vec3 decaying=oldEnergy*retention;
    vec3 nextEnergy=mix(decaying,rising,step(oldEnergy,exposure));
    gl_FragColor=vec4(nextEnergy,1.0);
  }
`));
gl.linkProgram(feedbackProgram);
const feedbackPosition = gl.getAttribLocation(feedbackProgram, 'p');
