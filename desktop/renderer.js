window.addEventListener('focus', resetKeyboardState);
document.addEventListener('visibilitychange', () => {
  if (document.hidden) resetKeyboardState();
});
ipcRenderer.on('terminal:resume', () => {
  resetKeyboardState();
  term.scrollToBottom();
});

