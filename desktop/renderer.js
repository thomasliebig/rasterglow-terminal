function resize() {
  const dpr = Math.min(2, Math.max(1.75, devicePixelRatio || 1));
  const width = screen.clientWidth;
  const height = screen.clientHeight;
  canvas.width = current.width = Math.floor(width * dpr);
  canvas.height = current.height = Math.floor(height * dpr);
  canvas.style.width = width + 'px';
  canvas.style.height = height + 'px';

  // A rectangular PTY must fit inside the narrowest part of the barrel-
  // distorted glass. TUIs otherwise use columns that disappear at corners.
  textLeft = Math.round(width * 0.075);
  textTop = Math.round(height * 0.045);
  const usableW = width * 0.85;
  const usableH = height * 0.90;
  fontSize = Math.max(12, Math.min(22, usableH / 38 * 0.76));
  cellH = fontSize * 1.28;

  cctx.font = `${fontSize * dpr}px ${fontFamily}`;
  cellW = cctx.measureText('M').width / dpr;
  cols = Math.max(20, Math.floor(usableW / cellW));
  // AsciiTeX output is 108 cells wide. Keep a safety margin so a full line
  // never reaches xterm's delayed-wrap column.
  if (cols < 120) {
    fontSize = Math.max(9, fontSize * (cols / 120) * 0.97);
    cellH = fontSize * 1.28;
    cctx.font = `${fontSize * dpr}px ${fontFamily}`;
    cellW = cctx.measureText('M').width / dpr;
    cols = Math.max(20, Math.floor(usableW / cellW));
  }
  rows = Math.max(8, Math.floor(usableH / cellH));
  term.resize(cols, rows);
  window.retroTerminal.resize(cols, rows);
  allocateEnergyTextures();
  updateStatus();
}

function renderCurrent(dpr) {
  cctx.clearRect(0, 0, current.width, current.height);
  cctx.save();
  cctx.scale(dpr, dpr);
  cctx.font = `${fontSize}px ${fontFamily}`;
  cctx.fontKerning = 'none';
  cctx.textBaseline = 'top';
  cctx.shadowBlur = 0;

  const buffer = term.buffer.active;
  // Paint backgrounds first, including cells containing spaces. ANSI 16/256/
  // RGB backgrounds therefore remain real rectangular terminal cells.
  for (let y = 0; y < rows; y++) {
    const line = buffer.getLine(buffer.viewportY + y);
    if (!line) continue;
    for (let x = 0; x < cols; x++) {
      const cell = line.getCell(x);
      if (!cell) continue;
      const paint = cellPaint(cell);
      if (paint.bg) {
        cctx.globalAlpha = 1;
        cctx.fillStyle = paint.bg;
        cctx.fillRect(textLeft + x * cellW, textTop + y * cellH, cellW + 0.35, cellH + 0.35);
      }
    }
  }
  for (let y = 0; y < rows; y++) {
    const line = buffer.getLine(buffer.viewportY + y);
    if (!line) continue;
    // xterm's buffer owns the grid. Draw every glyph at its absolute cell
    // coordinate without cumulative text-run advances. Narrow fallback glyphs
    // are centered, while only over-wide glyphs are compressed into their
    // xterm-owned cell span; nothing is stretched to fake monospace.
    for (let x = 0; x < cols; x++) {
      const cell = line.getCell(x);
      if (!cell) continue;
      const chars = cell.getChars();
      if (!chars) continue;
      if (cell.isBlink() && !blinkVisible) continue;
      const cellSpan = Math.max(1, cell.getWidth());
      const paint = cellPaint(cell);
      cctx.globalAlpha = cell.isDim() ? 0.42 : 0.72;
      cctx.fillStyle = paint.fg;
      cctx.shadowColor = paint.fg;
      const targetW = cellW * cellSpan;
      const measured = cctx.measureText(chars).width;
      const originX = textLeft + x * cellW;
      cctx.save();
      cctx.translate(originX, textTop + y * cellH);
      if (measured > targetW * 1.015) cctx.scale(targetW / measured, 1);
      cctx.textAlign = 'left';
      cctx.fillText(chars, 0, 0);
      cctx.restore();
      if (cell.isUnderline()) {
        cctx.globalAlpha = 0.72;
        cctx.fillStyle = paint.fg;
        cctx.fillRect(textLeft + x * cellW, textTop + (y + 0.89) * cellH, targetW, Math.max(1, fontSize / 14));
      }
      if (cell.isOverline()) {
        cctx.globalAlpha = 0.72;
        cctx.fillStyle = paint.fg;
        cctx.fillRect(textLeft + x * cellW, textTop + y * cellH + Math.max(0.5, fontSize * 0.03), targetW, Math.max(1, fontSize / 14));
      }
      x += cellSpan - 1;
    }
  }

  if (cursorVisible) {
    cctx.globalAlpha = 1;
    cctx.fillStyle = 'rgba(150,255,185,0.78)';
    cctx.fillRect(textLeft + buffer.cursorX * cellW, textTop + buffer.cursorY * cellH + cellH * .82, cellW, 2.5);
  }
  if (mouseTestOverlay) {
    cctx.globalAlpha = 0.96;
    cctx.fillStyle = 'rgba(0,12,5,0.94)';
    cctx.fillRect(textLeft, textTop + 4 * cellH, Math.min(760, cols * cellW), cellH * 1.15);
    cctx.fillStyle = 'rgb(72,255,132)';
    cctx.font = `${fontSize}px ${fontFamily}`;
    cctx.textAlign = 'left';
    cctx.fillText(mouseTestMessage, textLeft, textTop + 4 * cellH);
  }
  if (mouseCalibration) {
    cctx.globalAlpha = 0.95;
    cctx.font = `${fontSize}px ${fontFamily}`;
    cctx.textAlign = 'left';
    for (const target of calibrationTargets()) {
      const x = textLeft + target.col * cellW;
      const y = textTop + target.row * cellH;
      cctx.fillStyle = 'rgba(4,55,22,0.92)';
      cctx.fillRect(x, y, 13 * cellW, 3 * cellH);
      cctx.strokeStyle = 'rgb(72,255,132)';
      cctx.lineWidth = 1.5;
      cctx.strokeRect(x, y, 13 * cellW, 3 * cellH);
      cctx.fillStyle = 'rgb(72,255,132)';
      cctx.fillText(target.name, x + cellW, y + cellH * 0.72);
    }
    cctx.fillStyle = 'rgba(0,10,4,0.96)';
    cctx.fillRect(textLeft, textTop, Math.min(cols * cellW, 900), cellH * 2.2);
    cctx.fillStyle = 'rgb(92,255,148)';
    cctx.fillText(calibrationMessage, textLeft + cellW, textTop + cellH * 0.45);
  }
  cctx.restore();
}

function animate(now) {
  const dpr = Math.min(2, Math.max(1.75, devicePixelRatio || 1));
  const dt = Math.min(0.1, (now - last) / 1000);
  last = now;
  cursorVisible = Math.floor(now / 520) % 2 === 0;
  blinkVisible = Math.floor(now / 500) % 2 === 0;
  const activeBuffer = term.buffer.active;
  const alternateBuffer = activeBuffer === term.buffer.alternate;
  const bufferSwitched = alternateBuffer !== lastAlternateBuffer;
  if (bufferSwitched) {
    lastAlternateBuffer = alternateBuffer;
    // Never blend a full-screen TUI with the shell that replaces it. They are
    // distinct CRT pages, not two exposures of the same character cells.
    allocateEnergyTextures();
    lastScrollAt = now;
  }
  const bufferAdvanced = activeBuffer.baseY !== lastBaseY;
  if (bufferAdvanced) {
    lastBaseY = activeBuffer.baseY;
    lastScrollAt = now;
  }
  renderCurrent(dpr);

  // Persistence is spatially neutral: vertical scrolling must retain the
  // same per-pixel phosphor energy as horizontal edits. Only a true buffer
  // page switch clears exposure; active redraw merely decays somewhat faster.
  const activelyRedrawing = now - lastTerminalDataAt < 180;
  const halfLife = now - lastScrollAt < 320 ? 0.22 : activelyRedrawing ? 0.28 : 0.65;
  const retention = bufferSwitched ? 0.0 : Math.pow(0.5, dt / halfLife);
  const charge = 1.0 - Math.exp(-dt / 0.14);
  gl.bindTexture(gl.TEXTURE_2D, glTexture);
  gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, current);

  const nextEnergy = 1 - energyIndex;
  gl.bindFramebuffer(gl.FRAMEBUFFER, energyFramebuffers[nextEnergy]);
  gl.viewport(0, 0, canvas.width, canvas.height);
  gl.useProgram(feedbackProgram);
  gl.bindBuffer(gl.ARRAY_BUFFER, glBuffer);
  gl.enableVertexAttribArray(feedbackPosition);
  gl.vertexAttribPointer(feedbackPosition,2,gl.FLOAT,false,0,0);
  gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, energyTextures[energyIndex]);
  gl.uniform1i(gl.getUniformLocation(feedbackProgram,'previousEnergy'),0);
  gl.activeTexture(gl.TEXTURE1); gl.bindTexture(gl.TEXTURE_2D, glTexture);
  gl.uniform1i(gl.getUniformLocation(feedbackProgram,'currentLight'),1);
  gl.uniform1f(gl.getUniformLocation(feedbackProgram,'retention'),retention);
  gl.uniform1f(gl.getUniformLocation(feedbackProgram,'charge'),charge);
  gl.drawArrays(gl.TRIANGLES,0,3);
  energyIndex=nextEnergy;

  gl.bindFramebuffer(gl.FRAMEBUFFER, null);
  gl.viewport(0, 0, canvas.width, canvas.height);
  gl.useProgram(glProgram);
  gl.bindBuffer(gl.ARRAY_BUFFER, glBuffer);
  gl.enableVertexAttribArray(glPosition);
  gl.vertexAttribPointer(glPosition,2,gl.FLOAT,false,0,0);
  gl.activeTexture(gl.TEXTURE0);
  gl.bindTexture(gl.TEXTURE_2D, energyTextures[energyIndex]);
  gl.uniform1i(gl.getUniformLocation(glProgram,'phosphor'),0);
  gl.activeTexture(gl.TEXTURE1);
  gl.bindTexture(gl.TEXTURE_2D, glTexture);
  gl.uniform1i(gl.getUniformLocation(glProgram,'liveText'),1);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'barrel'), 0.015 + geometry.curve * 0.0045);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'brightness'), geometry.brightness);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'contrast'), geometry.contrast);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'focus'), geometry.focus);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'glow'), geometry.glow);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'flicker'), geometry.flicker);
  gl.uniform1f(gl.getUniformLocation(glProgram, 'time'), now / 1000);
  gl.uniform2f(gl.getUniformLocation(glProgram, 'resolution'), canvas.width, canvas.height);
  gl.drawArrays(gl.TRIANGLES, 0, 3);
  requestAnimationFrame(animate);
}

const mouseMode = { tracking: 'none', sgr: false, win32Input: false, tail: '' };

function hexText(text) {
  return [...new TextEncoder().encode(text)].map(value => value.toString(16).padStart(2, '0')).join('');
}

function reportTerminalCapabilities(probe, oldTailLength) {
  const isNew = match => match.index + match[0].length > oldTailLength;
  let match;

  const decrqm = /\x1b\[\?(\d+)\$p/g;
  while ((match = decrqm.exec(probe))) if (isNew(match)) {
    const mode = +match[1];
    const protocol = term._core?.coreMouseService?.activeProtocol;
    const encoding = term._core?.coreMouseService?.activeEncoding;
    let status = 0;
    const known = set => { status = set ? 1 : 2; };
    if (mode === 1000) known(protocol === 'VT200');
    else if (mode === 1002) known(protocol === 'DRAG');
    else if (mode === 1003) known(protocol === 'ANY' || forcedMouseCapture);
    else if (mode === 1006) known(encoding === 'SGR' || forcedMouseCapture);
    else if (mode === 1049) known(term.buffer.active === term.buffer.alternate);
    else if (mode === 2004) known(term.modes.bracketedPasteMode);
    else if (mode === 1) known(term.modes.applicationCursorKeysMode);
    else if (mode === 6) known(term.modes.originMode);
    else if (mode === 7) known(term.modes.wraparoundMode);
    else if (mode === 25) known(true);
    window.retroTerminal.input(`\x1b[?${mode};${status}$y`);
  }

  const xtversion = /\x1b\[>\d*q/g;
  while ((match = xtversion.exec(probe))) if (isNew(match))
    window.retroTerminal.input('\x1bP>|RasterGlow-Terminal 1.0.0\x1b\\');

  const xtget = /\x1bP\+q([0-9a-fA-F;]+)\x1b\\/g;
  while ((match = xtget.exec(probe))) if (isNew(match)) {
    const values = {
      TN: 'xterm-256color', Co: '256', RGB: '8/8/8',
      Tc: true
    };
    for (const encodedName of match[1].split(';')) {
      const name = new TextDecoder().decode(Uint8Array.from(encodedName.match(/../g) || [], byte => parseInt(byte, 16)));
      if (!(name in values)) window.retroTerminal.input(`\x1bP0+r${encodedName}\x1b\\`);
      else {
        const value = values[name];
        window.retroTerminal.input(`\x1bP1+r${encodedName}${value === true ? '' : '=' + hexText(value)}\x1b\\`);
      }
    }
  }

  const oscColor = /\x1b\](10|11);\?(?:\x07|\x1b\\)/g;
  while ((match = oscColor.exec(probe))) if (isNew(match)) {
    const rgb = match[1] === '10' ? '2aff/ffff/66ff' : '0000/0500/0300';
    window.retroTerminal.input(`\x1b]${match[1]};rgb:${rgb}\x1b\\`);
  }

  const winQuery = /\x1b\[(14|16)t/g;
  while ((match = winQuery.exec(probe))) if (isNew(match)) {
    if (match[1] === '14') window.retroTerminal.input(`\x1b[4;${screen.clientHeight};${screen.clientWidth}t`);
    else window.retroTerminal.input(`\x1b[6;${Math.round(cellH)};${Math.round(cellW)}t`);
  }
}

function observeTerminalModes(data) {
  const oldTailLength = mouseMode.tail.length;
  const probe = mouseMode.tail + data;
  reportTerminalCapabilities(probe, oldTailLength);
  if (probe.includes('\x1b]777;mouse=on\x07')) {
    forcedMouseCapture = true;
    mouseTestOverlay = true;
    mouseDiagnostic = 'MAUS SGR AKTIV';
    updateStatus();
  }
  if (probe.includes('\x1b]777;mouse=off\x07')) {
    forcedMouseCapture = false;
    mouseTestOverlay = false;
    mouseDiagnostic = '';
    updateStatus();
  }
  if (probe.includes('\x1b]777;mouse=calibrate\x07')) {
    forcedMouseCapture = true;
    mouseTestOverlay = false;
    mouseCalibration = true;
    mouseDiagnostic = 'MAUS-KALIBRIERUNG';
    updateStatus();
  }
  if (probe.includes('\x1b]777;mouse=calibrate-off\x07')) {
    forcedMouseCapture = false;
    mouseCalibration = false;
    mouseDiagnostic = '';
    updateStatus();
  }
  const re = /\x1b\[\?([0-9;]+)([hl])/g;
  let match;
  while ((match = re.exec(probe))) {
    const enabled = match[2] === 'h';
    for (const mode of match[1].split(';')) {
      if (mode === '9001') mouseMode.win32Input = enabled;
      else if (mode === '1006') mouseMode.sgr = enabled;
      else if (['1000','1002','1003'].includes(mode) && enabled) mouseMode.tracking = mode;
      else if (mouseMode.tracking === mode) mouseMode.tracking = 'none';
    }
    if (match[1].split(';').some(mode => ['1000','1002','1003','1006'].includes(mode)))
      mouseDiagnostic = enabled ? `MAUS ${match[1]} AKTIV` : '';
    updateStatus();
  }
  mouseMode.tail = probe.slice(-64);
}

window.retroTerminal.onData(data => {
  lastTerminalDataAt = performance.now();
  observeTerminalModes(data);
  // xterm-headless currently ignores SGR 6 (rapid blink). Preserve terminal
  // semantics by degrading it to supported SGR 5 instead of printing or
  // silently losing the attribute.
  const normalized = data.replace(/\x1b\[([0-9;]*)m/g, (sequence, parameters) => {
    const values = parameters.split(';');
    return values.includes('6') ? `\x1b[${values.map(value => value === '6' ? '5' : value).join(';')}m` : sequence;
  });
  term.write(normalized);
});
window.retroTerminal.onExit(() => term.write('\r\n\x1b[31m[PowerShell beendet]\x1b[0m'));

function terminalMouseCell(event) {
  const rect = screen.getBoundingClientRect();
  const uvx = (event.clientX - rect.left) / rect.width;
  const uvy = 1 - (event.clientY - rect.top) / rect.height;
  const qx = uvx * 2 - 1, qy = uvy * 2 - 1;
  const barrel = 0.015 + geometry.curve * 0.0045;
  const factor = 1 + barrel * (qx * qx + qy * qy);
  const sourceX = (qx * factor + 1) * 0.5 * screen.clientWidth;
  const sourceY = (1 - (qy * factor + 1) * 0.5) * screen.clientHeight;
  return {
    col: Math.max(0, Math.min(cols - 1, Math.floor((sourceX - textLeft) / cellW))),
    row: Math.max(0, Math.min(rows - 1, Math.floor((sourceY - textTop) / cellH))),
    x: Math.max(1, Math.round(sourceX)),
    y: Math.max(1, Math.round(sourceY))
  };
}

let pressedMouseButton = -1;
function sendMouse(event, button, action) {
  const cell = terminalMouseCell(event);
  const tracking = forcedMouseCapture ? '1003' : mouseMode.tracking;
  const isMove = action === 32;
  if (tracking === 'none' || (isMove && tracking === '1000') || (isMove && tracking === '1002' && pressedMouseButton < 0)) return false;
  const packet = sgrMouseSequence({
    button, action, col: cell.col, row: cell.row,
    shiftKey: event.shiftKey, altKey: event.altKey, ctrlKey: event.ctrlKey
  });
  window.retroTerminal.input(packet);
  const sent = true;
  if (sent) {
    const names = action === 32 ? 'MOVE' : button === 4 ? (action === 0 ? 'RAD↑' : 'RAD↓') : action === 0 ? 'UP' : 'DOWN';
    mouseDiagnostic = `MAUS ${names} C${cell.col + 1} R${cell.row + 1}`;
    mouseTestMessage = `Event: ${names}   column=${cell.col + 1}   row=${cell.row + 1}   SGR forwarded to ConPTY`;
    updateStatus();
  }
  return sent;
}

screen.addEventListener('pointerdown', event => {
  const button = event.button === 0 ? 0 : event.button === 1 ? 1 : event.button === 2 ? 2 : -1;
  if (button === 0 && mouseCalibration) {
    const cell = terminalMouseCell(event);
    const targets = calibrationTargets();
    const nearest = targets.reduce((best, target) => {
      const centerCol = target.col + 6, centerRow = target.row + 1;
      const distance = Math.hypot(cell.col - centerCol, cell.row - centerRow);
      return !best || distance < best.distance ? { target, centerCol, centerRow, distance } : best;
    }, null);
    calibrationMessage = `${nearest.target.name}: clicked C${cell.col + 1}/R${cell.row + 1}, target center C${nearest.centerCol + 1}/R${nearest.centerRow + 1}, error ΔC=${cell.col - nearest.centerCol}, ΔR=${cell.row - nearest.centerRow}`;
  }
  if (button >= 0 && sendMouse(event, button, 1)) {
    pressedMouseButton = button;
    screen.setPointerCapture(event.pointerId);
    event.preventDefault();
  }
});
screen.addEventListener('pointerup', event => {
  if (pressedMouseButton >= 0 && sendMouse(event, pressedMouseButton, 0)) event.preventDefault();
  pressedMouseButton = -1;
});
screen.addEventListener('pointermove', event => {
  if (sendMouse(event, pressedMouseButton >= 0 ? pressedMouseButton : 3, 32)) event.preventDefault();
});
screen.addEventListener('wheel', event => {
  if (sendMouse(event, 4, event.deltaY < 0 ? 0 : 1)) event.preventDefault();
}, { passive: false });
screen.addEventListener('contextmenu', event => {
  if (mouseMode.tracking !== 'none' || forcedMouseCapture) event.preventDefault();
});

const pressedKeys = new Set();
const interceptedKeyUps = new Set();
function resetKeyboardState() {
  pressedKeys.clear();
  interceptedKeyUps.clear();
}

function reconcileModifierState(event) {
  // Browsers do not dispatch keyup when focus is lost while a modifier is
  // held. Remove those stale keys before encoding the next Win32 record.
  if (!event.shiftKey) { pressedKeys.delete('ShiftLeft'); pressedKeys.delete('ShiftRight'); }
  if (!event.ctrlKey) { pressedKeys.delete('ControlLeft'); pressedKeys.delete('ControlRight'); }
  if (!event.altKey) { pressedKeys.delete('AltLeft'); pressedKeys.delete('AltRight'); }
  if (!event.metaKey) { pressedKeys.delete('MetaLeft'); pressedKeys.delete('MetaRight'); }
}

window.addEventListener('keydown', event => {
  reconcileModifierState(event);
  if (event.ctrlKey && event.shiftKey && event.key === 'F2') {
    interceptedKeyUps.add(event.code);
    document.getElementById('controls').classList.toggle('hidden');
    event.preventDefault(); return;
  }
  if (event.ctrlKey && event.shiftKey && event.key === 'F3') {
    interceptedKeyUps.add(event.code);
    forcedMouseCapture = !forcedMouseCapture;
    mouseDiagnostic = forcedMouseCapture ? 'MAUS SGR MANUELL' : '';
    updateStatus();
    event.preventDefault(); return;
  }
  if (event.ctrlKey && event.shiftKey && event.key === 'F11') {
    interceptedKeyUps.add(event.code);
    ipcRenderer.send('window:fullscreen');
    event.preventDefault(); return;
  }
  if (event.ctrlKey && event.shiftKey && event.key.toLowerCase() === 'v') {
    interceptedKeyUps.add(event.code);
    term.scrollToBottom();
    navigator.clipboard.readText().then(text => window.retroTerminal.input(text));
    event.preventDefault(); return;
  }
  if (mouseMode.win32Input) {
    pressedKeys.add(event.code);
    const locks = { num: event.getModifierState('NumLock'), scroll: event.getModifierState('ScrollLock'), caps: event.getModifierState('CapsLock'), pressed: pressedKeys };
    term.scrollToBottom();
    window.retroTerminal.input(win32KeySequence(event, true, locks));
    event.preventDefault(); return;
  }
  if (event.ctrlKey && event.key.toLowerCase() === 'c') {
    term.scrollToBottom();
    window.retroTerminal.input('\x03'); event.preventDefault(); return;
  }
  if (event.ctrlKey && !event.altKey && !event.metaKey) {
    const key = event.key.toLowerCase();
    let control = null;
    if (key.length === 1 && key >= 'a' && key <= 'z') control = String.fromCharCode(key.charCodeAt(0) - 96);
    else if (key === ' ' || key === '@') control = '\x00';
    else if (key === '[') control = '\x1b';
    else if (key === '\\') control = '\x1c';
    else if (key === ']') control = '\x1d';
    else if (key === '^') control = '\x1e';
    else if (key === '_') control = '\x1f';
    else if (key === '?') control = '\x7f';
    if (control !== null) {
      term.scrollToBottom();
      window.retroTerminal.input(control);
      event.preventDefault(); return;
    }
  }
  const special = {
    Enter: '\r', Backspace: '\x7f', Tab: '\t', Escape: '\x1b',
    ArrowUp: '\x1b[A', ArrowDown: '\x1b[B', ArrowRight: '\x1b[C', ArrowLeft: '\x1b[D',
    Home: '\x1b[H', End: '\x1b[F', Delete: '\x1b[3~', PageUp: '\x1b[5~', PageDown: '\x1b[6~'
  };
  if (special[event.key]) { term.scrollToBottom(); window.retroTerminal.input(special[event.key]); event.preventDefault(); }
  else if (event.key.length === 1 && !event.ctrlKey && !event.metaKey) {
    term.scrollToBottom();
    window.retroTerminal.input(event.key); event.preventDefault();
  }
}, true);

window.addEventListener('keyup', event => {
  if (interceptedKeyUps.delete(event.code)) { event.preventDefault(); return; }
  if (!mouseMode.win32Input) return;
  pressedKeys.delete(event.code);
  const locks = { num: event.getModifierState('NumLock'), scroll: event.getModifierState('ScrollLock'), caps: event.getModifierState('CapsLock'), pressed: pressedKeys };
  window.retroTerminal.input(win32KeySequence(event, false, locks));
  event.preventDefault();
}, true);

